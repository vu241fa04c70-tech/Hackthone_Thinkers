export function getLocalizedLocationName(rawLocation, langCode = 'te') {
  if (!rawLocation) return '';
  const lang = (langCode || 'en').toLowerCase();

  let text = String(rawLocation);

  // Replace each known city/state substring with its translated equivalent
  for (const [key, transObj] of Object.entries(LOCATION_TRANSLATIONS)) {
    const localizedWord = transObj[lang] || transObj.te || transObj.en || key;
    const regex = new RegExp(`\\b${key}\\b`, 'gi');
    text = text.replace(regex, localizedWord);
  }

  return text;
}
