export function translateMarketTerm(term, langCode = 'te') {
  if (!term) return '';
  const lang = (langCode || 'en').toLowerCase();
  const key = String(term).trim();

  const matchKey = Object.keys(MARKET_TRANSLATIONS).find(k => k.toLowerCase() === key.toLowerCase());
  if (matchKey) {
    const obj = MARKET_TRANSLATIONS[matchKey];
    return obj[lang] || obj.te || obj.en || key;
  }

  return key;
}
