export function translateWeatherTerm(term, langCode = 'te') {
  if (!term) return '';
  const lang = (langCode || 'en').toLowerCase();
  const key = String(term).trim();

  const matchKey = Object.keys(WEATHER_TRANSLATIONS).find(k => k.toLowerCase() === key.toLowerCase());
  if (matchKey) {
    const obj = WEATHER_TRANSLATIONS[matchKey];
    return obj[lang] || obj.te || obj.en || key;
  }

  return key;
}

export function translateRainLabel(langCode = 'te') {
  const lang = (langCode || 'en').toLowerCase();
  if (lang === 'te') return 'వర్షం';
  if (lang === 'hi') return 'बारिश';
  if (lang === 'ta') return 'மழை';
  if (lang === 'kn') return 'ಮಳೆ';
  return 'Rain';
}

export function translateHumidityLabel(langCode = 'te') {
  const lang = (langCode || 'en').toLowerCase();
  if (lang === 'te') return 'తేమ శాతము';
  if (lang === 'hi') return 'आर्द्रता';
  if (lang === 'ta') return 'ஈரப்பதம்';
  if (lang === 'kn') return 'ತೇವಾಂಶ';
  return 'Humidity';
}

export function translateMmRainLabel(val, langCode = 'te') {
  const lang = (langCode || 'en').toLowerCase();
  if (lang === 'te') return `${val} మి.మీ వర్షం`;
  if (lang === 'hi') return `${val} मिमी बारिश`;
  if (lang === 'ta') return `${val} மி.மீ மழை`;
  if (lang === 'kn') return `${val} ಮಿ.ಮೀ ಮಳೆ`;
  return `${val} mm rain`;
}
